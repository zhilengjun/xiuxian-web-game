// 全局数值常量（数据驱动的唯一出处）。
// 依据：AGENTS §3「数值一律来自 src/config/，逻辑层不得硬编码」。
//
// 【单位约定，2026-09-15 变更】全项目统一使用 **像素（px）**，不再有「世界单位 u」这一层抽象。
//   - 逻辑层与渲染层用同一套数值：1 逻辑单位 = 设计分辨率 1920×1080 下的 1 屏幕像素。
//   - 实体外观尺寸已按设计者指示缩小到 1/3 左右：**玩家直径 84px / 小怪 42px / BOSS 252px**
//     （比例仍是 GDD §3.2 的 2:1:6；换算系数 = 21/64）。详见下方「实体尺寸」段注释。
//   - 由此得到的非整数是**刻意保留的精确值**：例如碰撞半径 29.4 = 42 × 0.7，不四舍五入，
//     以保证 GDD §14「碰撞半径 = 外观半径 × 0.7」严格成立。
//   - 移植到其它分辨率（如小游戏）时，整体缩放放在渲染层（View 按窗口缩放画布），
//     不再依靠 u 换算 —— 见 README §5。
(function () {
  const HX = window.HX || (window.HX = {});

  const DESIGN_W = 1920, DESIGN_H = 1080;
  const MAP_W = 5760, MAP_H = 3240;   // GDD §3：3×3 屏拼接

  const C = {
    // ---- 屏幕 / 地图（GDD §3）。（历史上这些值以 u 表达，现全部为 px） ----
    DESIGN_W_PX: DESIGN_W,
    DESIGN_H_PX: DESIGN_H,
    MAP_W: MAP_W,                        // 5760 px
    MAP_H: MAP_H,                        // 3240 px
    // 视口 = 一屏。设计分辨率下 1 逻辑单位 = 1 屏幕像素，所以视口尺寸等于画布尺寸。
    VIEW_W: DESIGN_W,
    VIEW_H: DESIGN_H,
    ARENA: { w: MAP_W, h: MAP_H },

    // ---- 循环（README §9） ----
    FIXED_DT: 1 / 60,                    // 逻辑 60Hz
    MAX_STEPS: 5,                        // 单帧最多追帧
    SEED: 20260915,                      // 默认种子（GDD 定稿日）

    // ---- 实体尺寸（GDD §3.2；碰撞半径 = 外观半径 × 0.7，GDD §14） ----
    // 【2026-09-15 设计者指示：实体太大 → 全部缩小到原来的 1/3 左右】
    // 换算系数 = 84 / 256 = 21/64 ≈ 0.328（玩家外观直径 256px → 84px）。
    // 比例 玩家:小怪:BOSS = 2:1:6 保持不变 → 直径 84 / 42 / 252。
    // ⚠ 只有"实体自身尺寸"与"以身位（玩家直径）计的距离"参与缩放；
    //   射程/范围/半径（GDD §3.1 按屏幕比例定义，如御剑 3072、雷池 768、雷霆 2048）
    //   与全部速度（px/s）**不变** —— 它们是屏幕尺度与手感参数，不是实体大小。
    // 2026-09-15 设计者指示：主角移速降为原本的 1/2（1280 → 640）。
    PLAYER: { visualR: 42, solidR: 29.4, speed: 640 },     // 外观直径 84px ｜ 640px/s
    ENEMY: { visualR: 21, solidR: 14.7 },                  // 外观直径 42px
    BOSS: { visualR: 126, solidR: 88.2, speed: 128 },      // 外观直径 252px ｜ 128px/s

    // 弹幕（GDD §14）：判定比外观小；尺寸按身位比例（0.15/0.1、0.2/0.12 身位）同步缩小
    PBULLET: { visualR: 12.6, solidR: 8.4 },
    EBULLET: { visualR: 16.8, solidR: 10.08 },

    // ---- 地图边界（GDD §5：空气墙 / 灵气屏障） ----
    WALL_MARGIN: 29.4,

    // ---- 相机（GDD §5；纵向构图偏移见 §3.3 表现层） ----
    // deadzone：死区占屏比（50%~60% 范围内镜头不动，GDD §5 原文）
    // yOffset ：瞄准点上移量（暂定，纯表现层构图）= 玩家立绘高度的一半（113.4 / 2）。
    //           立绘是从**脚下锚点向上站立**的；若瞄准点就停在脚下，角色走到纵向死区上沿
    //           （距屏幕中心 1080×0.55/2 = 297px）时头顶会出画。上移瞄准点让角色坐在画面偏下。
    //           这**不改变 GDD §5 的死区规则**（水平仍是 55%），只是换了瞄准点。改 0 即还原。
    CAMERA: { deadzone: 0.55, yOffset: 56.7 },

    // ---- 石柱位置（GDD §13.3：场地四角） ----
    // solidForPlayer（暂定）：石柱是否阻挡**玩家**移动。GDD 只说「不可攻击、不可摧毁」，
    //   没说是否可穿过。取 true —— 与侧视立绘里「它是一根立在地上的柱子」一致；
    //   小怪与 BOSS **不受**石柱阻挡（GDD §14 未规定，取"不卡怪不被柱子挡住追击路径"）。
    //   要关掉阻挡只改这一处（false）。
    // 石柱（GDD §13.3 + 2026-09-16 设计者指示「屏幕四角定位 + 结界围困」）：
    //   inset    = 柱心距"召唤时玩家所在屏幕"四角的内缩距离（暂定 140px ——
    //              柱立绘高 193px 且从锚点向上生长，柱身基本完整落在屏内）。
    //   barrierInset = 结界边界距屏幕四角的内缩（= 玩家碰撞半径 29.4）。
    //              2026-09-16 二次指示「结界向外推、贴近屏幕、把石柱全部包住」：
    //              结界从"柱心连线"外推到屏边内侧 —— 柱面最外距屏边 140-46.2=93.8px，
    //              全部落在结界内；玩家中心被 clamp 在结界内 → 玩家边缘恰好贴屏边。
    //   emergeTime = 石柱上升时长（2026-09-16 设计者指示：0.8 → 2.0，单轴缩放 0→1，
    //              与 BOSS 召唤施法同步开始/结束；出土完成前无碰撞）。
    PILLAR: { count: 4, solidR: 46.2, visualR: 58.8, inset: 140, barrierInset: 29.4,
              solidForPlayer: true, emergeTime: 2.0 },

    // ---- 弹幕速度（单点开关） ----
    // 设计者 2026-09-15 指示：所有弹幕速度统一为 **512 px/s**，后续再逐个调。
    // skins.js / enemies.js / boss.js 的弹速全部引用这里，要改只改这一行。
    // ⚠ GDD §13.3 原把 BOSS 追踪弹定义为「玩家 80% = 1024px/s」，与本次统一值冲突，
    //   已在 config/boss.js 内注明如何一键恢复。
    BULLET_SPEED: 512,

    // ---- 表现层（斜俯视地面 + 侧视立绘，见 GDD §3.3） ----
    // 立绘**宽度**沿用 §3.2 的「世界外观直径」（= 资源基准 px）；高度原 GDD 未定义，现暂定。
    // 全部为 px。shadow* 为落地阴影（椭圆）的宽/高。尺寸已随实体一并 ×21/64。
    VISUAL: {
      player: { w: 84, h: 113.4, shadowW: 68.88, shadowH: 23.52 },
      spider: { w: 42, h: 40.32, shadowW: 36.96, shadowH: 12.6 },     // 血魔蛛：低伏造型
      wizard: { w: 42, h: 82.32, shadowW: 28.56, shadowH: 10.08 },     // 邪修术士：漂浮长袍
      boss:   { w: 252, h: 302.4, shadowW: 176.4, shadowH: 52.08 },    // 吞天老祖：巨型悬浮
      pillar: { w: 117.6, h: 193.2, shadowW: 92.4, shadowH: 28.56 },   // 石柱：立柱 + 顶盖
      pickup: { w: 42, h: 52.08, shadowW: 25.2, shadowH: 9.24 }        // 护身灵石：悬浮
    },

    // 斜俯视投影：地面平面上的**圆**在屏幕上的纵向压缩比（1 = 正俯视，越小越"斜"）。
    // 用于把平面标记画成椭圆（环绕轨道、雷池范围圈、地火预警、落地阴影），
    // 让"贴地的圆"与"竖立的立绘"在视觉上区分开。
    PLANE_SQUASH: 0.55,

    // 石柱召唤坐标（px，GDD §13.3 + 2026-09-16 设计者指示）：
    // 以"召唤时玩家所在的屏幕"（相机视口 = 设计分辨率 1920×1080）四角内缩 inset 定位，
    // 保证柱子落在屏内可见；4 柱连成矩形即灵气结界（把玩家围在中间，见 systems/movement.js）。
    // view 不传时按设计分辨率全屏算（等价于相机在地图原点）。
    pillarPositions(view) {
      const v = view || { x: 0, y: 0, w: C.VIEW_W, h: C.VIEW_H };
      const i = C.PILLAR.inset;
      return [
        { x: v.x + i, y: v.y + i },
        { x: v.x + v.w - i, y: v.y + i },
        { x: v.x + v.w - i, y: v.y + v.h - i },
        { x: v.x + i, y: v.y + v.h - i }
      ];
    }
  };

  HX.C = C;
})();
